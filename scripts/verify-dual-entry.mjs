import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const read = p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const home=read('apps/web/src/pages/HomePage.tsx');
const route=read('apps/web/src/main.tsx');
const candidate=read('apps/web/src/pages/CandidatePages.tsx');
const market=read('apps/web/src/components/UnifiedJobMarket.tsx');
const source=read('apps/web/src/services/liveRecruitment.ts');
const proxy=read('deploy/railway/web.mjs');

assert.equal((home.match(/<EntryCard\s/g)||[]).length,2,'homepage must keep exactly two role entry cards');
assert.ok(home.includes('我要应聘')&&home.includes('我要招人'));
assert.ok(home.includes("'/candidate'")&&home.includes("'/recruiter/register'"));
assert.ok(home.includes('<UnifiedJobMarket compact/>'));
assert.ok(home.indexOf('<UnifiedJobMarket compact/>')>home.lastIndexOf('<EntryCard'),'job listing is below role cards');
assert.ok(candidate.includes('to="/candidate/jobs"'),'candidate upload page must retain job entry');
assert.ok(route.includes("route==='/candidate/jobs'") && route.includes('<UnifiedJobMarket user={user}/>'));
assert.ok(route.includes("route==='/candidate/jobs/archive'"),'historical archive must not disappear');
assert.ok(route.includes('UnifiedJobDetail user={user}'),'same job detail page must serve shared results');
assert.ok(market.includes('listJobs(filters,page*30') && market.includes('getJob(jobId'));
assert.ok(market.includes("lang==='zh'")&&market.includes('English'),'language switch must be accessible');
assert.ok(market.includes("officialStatus(j,snapshot.updated)==='recent'"),'no unchecked historical jobs on default index');
assert.ok(source.includes("credentials: 'omit'"),'no account credentials to recruitment read-only API');
assert.ok(source.includes('hhba.jobs')===false,'source adapter must not access resume data');
assert.ok(source.includes('safeOfficialJobUrl'),'official URL checks mandatory');
assert.ok(proxy.includes('LIVE_API_PATH') && proxy.includes("method:'GET'"),'server must proxy approved GET paths only');
assert.ok(proxy.includes("if(!['GET','HEAD'].includes(req.method||''))"));
assert.ok(!market.includes('样例岗位')&&!market.includes('mockJobs'),'never invent jobs');
console.log('PASS: one white HHBA shell, two role entries, one shared live market and detail, historical archive retained.');
