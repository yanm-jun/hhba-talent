import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=x=>fs.readFileSync(x,'utf8');
const p=JSON.parse(read('src/data/employerProfiles/cn-autumn-035.json'));
assert.equal(p.id,'cn-autumn-035');
assert.equal(p.name,'佑驾创新');
assert.equal(p.englishName,'MINIEYE');
assert.equal(p.jobs.length,14);
assert.equal(p.business.length,6);
assert.equal(new Set(p.jobs.map(x=>x.id)).size,14);
assert(p.jobs.every(x=>x.summary.length>=45&&x.requirements.length>=145));
assert(p.jobs.every(x=>x.currentOpenVerified===false),'No 2027 position falsely marked currently open');
assert(p.jobs.every(x=>x.url.startsWith('https://app.mokahr.com/campus-recruitment/minieye/118571')));
assert(p.jobs.every(x=>x.evidenceUrl.startsWith('https://')),'All positions need a supporting source');
assert(!p.jobs.some(x=>x.title.includes('28届')),'2028 intern cannot be silently inserted into 2027 list');
const groups={'算法 / AI':4,'软件 / 数据':4,'嵌入式 / 硬件':2,'测试 / 验证':1,'项目 / 管培':2,'供应链':1};
assert.deepEqual(Object.keys(groups).sort(),[...new Set(p.jobs.map(x=>x.category))].sort());
for(const [cat,num] of Object.entries(groups))assert.equal(p.jobs.filter(x=>x.category===cat).length,num,cat);
assert.equal(p.jobs.filter(x=>x.category==='软件 / 数据'&&x.title.includes('C++')).length,1,'Do not duplicate same titled C++ roles');
assert(p.jobs.some(x=>x.title==='L4-感知算法工程师（2027届）'&&x.educationLabel.includes('硕士')));
assert(p.jobs.some(x=>x.id==='MJ000945'&&x.city==='上海'));
assert(p.jobs.some(x=>x.id==='MJ000944'&&x.city==='深圳'));
const page=read('src/pages/UnifiedV2CompanyPage.tsx'),css=read('src/styles/unified-v2-company.css');
assert(page.includes("minieye=id==='cn-autumn-035'"),'Use the same old V2 component');
assert(page.includes('if(minieye)return job.category===major'),'Filter the individual job category');
assert(page.includes('detailedCards=weipu||bodor||pxw||minieye||keyence'),'Second screenshot green expander');
assert(page.includes('data-hhba-recruitment-outbound="true"'),'Keep login first outbound');
assert(css.includes('.hhba-v2-minieye .hhba-v2-company-role'));
assert(css.includes('.hhba-v2-bodor .hhba-v2-company-role details summary'),'Inherit official V2 details style');
const names=[p.media.logo,...p.media.photos.map(x=>x.path)];
assert.equal(new Set(names).size,3);
for(const x of names)assert(fs.existsSync('public/'+x)&&fs.statSync('public/'+x).size>=2600,'Missing actual file '+x);
const provenance=JSON.parse(read('public/images/employer-profiles/cn-autumn-035/media-audit.json'));
assert.deepEqual(Object.keys(provenance).sort(),['logo.webp','photo1.jpg','photo2.jpg']);
assert(Object.values(provenance).every(x=>x.verified));
assert.equal(new Set(Object.values(provenance).map(x=>x.sha256)).size,3);
