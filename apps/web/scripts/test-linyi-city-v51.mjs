import assert from 'node:assert/strict';
import {TALENT_POLICY_RECORDS} from '../src/data/talentPolicyRecords.ts';
import {TALENT_HOUSING_RECORDS} from '../src/data/talentHousingRecords.ts';
import {assessPolicy,assessHousing,assessTalentCity} from '../src/data/talentQuality.ts';
import {linyiLivingGuide} from '../src/data/talentLinyiGuide.ts';
import {readFileSync} from 'node:fs';
const policies=TALENT_POLICY_RECORDS.filter(x=>x.city==='临沂');
const homes=TALENT_HOUSING_RECORDS.filter(x=>x.city==='临沂');
assert.equal(policies.length,4);
assert.equal(homes.length,19);
assert.equal(homes.reduce((n,h)=>n+Number(/配租分配项(\d+)套/.exec(h.units)?.[1]||0),0),896);
assert.ok(homes.every(h=>h.sourceUrl.includes('lyjs.linyi.gov.cn')&&h.applicationEnd==='2026-07-16'));
assert.ok(homes.every(h=>assessHousing(h,'2026-10-30').grade==='C'));
assert.ok(homes.every(h=>h.steps.length>=4&&h.contactPhone));
assert.ok(policies.every(x=>x.materials?.length>=3&&x.applicationSteps?.length>=4&&x.reviewedAt));
assert.ok(policies.every(x=>assessPolicy(x,'2026-10-30').grade==='B'),'No falsely A-certified Linyi policies');
assert.equal(assessTalentCity('临沂','2026-10-30').accepted,false);
assert.equal(linyiLivingGuide.steps.length,6);
assert.equal(linyiLivingGuide.faq.length,8);
assert.equal(Object.keys(linyiLivingGuide.branches).length,5);
const routes=readFileSync(new URL('../src/pages/TalentServiceRoutes.tsx',import.meta.url),'utf8');
assert.ok(routes.includes("fragments[2]==='linyi'"));
assert.ok(!routes.includes('TalentLinyiGuidePreview'));
const list=readFileSync(new URL('../src/components/talent/UnifiedPolicyList.tsx',import.meta.url),'utf8');
assert.ok(list.includes("p.id==='ly-youth-allowance-2026'"));
console.log('Linyi V5.1 PASS: four policy items, 19 expired housing allocations, 896 published units, shared route.');
