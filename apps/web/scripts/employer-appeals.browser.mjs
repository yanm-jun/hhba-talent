import {chromium} from 'playwright';
import {mkdirSync} from 'node:fs';
const base=(process.env.HHBA_TEST_BASE||'http://127.0.0.1:4173/hhba-talent/preview-employer/').replace(/\/$/,'');
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:900},locale:'zh-CN'});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
mkdirSync('appeals-review',{recursive:true});
try{
 await page.goto(base+'/',{waitUntil:'domcontentloaded',timeout:40000});
 await page.getByRole('button',{name:/我要招人/}).click();
 await page.getByRole('link',{name:/进入企业工作台/}).click();
 await page.getByRole('link',{name:'异议与申诉'}).click();
 await page.getByRole('heading',{name:'评分异议与复核'}).waitFor();
 await page.getByText('申诉业务服务尚未接通').waitFor();
 if(await page.getByRole('button',{name:'待安全申诉服务接入'}).isEnabled())throw Error('UNSAFE_EMPLOYER_APPEAL_ENABLED');
 await page.screenshot({path:'appeals-review/company-appeals-desktop.png',fullPage:true});
 await page.goto(base+'/employee/feedback/',{waitUntil:'domcontentloaded'});
 await page.getByRole('link',{name:/反馈过程有隐私疑虑/}).click();
 await page.getByRole('heading',{name:'员工隐私与反馈流程异议'}).waitFor();
 await page.getByText('真实员工隐私申诉尚未开放').waitFor();
 if(await page.getByRole('button',{name:'待可信员工验证接入'}).isEnabled())throw Error('UNSAFE_EMPLOYEE_APPEAL_ENABLED');
 if(await page.locator('textarea').count()>0)throw Error('EMPLOYEE_FREE_TEXT_LEAK_RISK');
 await page.screenshot({path:'appeals-review/employee-privacy-desktop.png',fullPage:true});
 await page.goto(base+'/admin/employer-appeals/',{waitUntil:'domcontentloaded'});
 await page.getByRole('heading',{name:'申诉处理工作台'}).waitFor();
 await page.getByText('独立申诉审核暂未接入').waitFor();
 if(await page.getByRole('button',{name:'待安全审核服务接入'}).isEnabled())throw Error('UNSAFE_REVIEW_ENABLED');
 await page.screenshot({path:'appeals-review/admin-review-disabled.png',fullPage:true});
 await page.goto(base+'/employer/appeals/',{waitUntil:'domcontentloaded'});
 await page.getByRole('heading',{name:'评分异议与复核'}).waitFor();
 await page.setViewportSize({width:390,height:844});
 await page.goto(base+'/employee/privacy-concerns/',{waitUntil:'domcontentloaded'});
 await page.getByRole('heading',{name:'员工隐私与反馈流程异议'}).waitFor();
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>document.documentElement.clientWidth+3);
 if(overflow)throw Error('APPEALS_MOBILE_HORIZONTAL_OVERFLOW');
 await page.screenshot({path:'appeals-review/employee-privacy-mobile.png',fullPage:true});
 if(errors.length)throw Error('BROWSER_ERRORS '+JSON.stringify(errors));
 console.log('HHBA_APPEALS_BROWSER_OK',JSON.stringify({enterpriseCase:true,employeePrivacy:true,independentAdmin:true,noFakeSubmissions:true,mobile:true,deepLinks:true}));
}finally{await browser.close()}
