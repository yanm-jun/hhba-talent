import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {TALENT_POLICY_RECORDS} from '../src/data/talentPolicyRecords.ts';
import {TALENT_HOUSING_RECORDS} from '../src/data/talentHousingRecords.ts';
import {assessPolicy,assessHousing,assessTalentCity} from '../src/data/talentQuality.ts';
import {dongyingTransitionGuide} from '../src/data/talentDongyingGuide.ts';
import {findTalentCity} from '../src/data/talentCityRegistry.ts';
const policies=TALENT_POLICY_RECORDS.filter(p=>p.city==='东营');
for(const id of ['sd-dongying-talent-2026','dy-home-history','dy-start-26'])assert.ok(policies.some(p=>p.id===id),'Existing ID missing '+id);
const old=policies.find(p=>p.id==='sd-dongying-talent-2026');
assert.equal(assessPolicy(old,'2026-10-30').grade,'C','2022 programme must be historical');
assert.ok(old.reviewNote.includes('9月30日'));
assert.equal(assessPolicy(policies.find(p=>p.id==='dy-home-history'),'2026-10-30').grade,'C');
assert.equal(assessTalentCity('东营','2026-10-30').accepted,false);
assert.equal(findTalentCity('dongying')?.name,'东营');
assert.equal(dongyingTransitionGuide.steps.length,6);
assert.ok(Object.keys(dongyingTransitionGuide.branches).length>=4);
assert.ok(dongyingTransitionGuide.faq.length>=6);
assert.equal(dongyingTransitionGuide.officialUrl,undefined,'No old application portal offered as new');
assert.ok(dongyingTransitionGuide.desc.includes('9月30日'));
const routes=readFileSync(new URL('../src/pages/TalentServiceRoutes.tsx',import.meta.url),'utf8');
assert.ok(routes.includes("fragments[2]==='dongying'"));
assert.ok(routes.includes('三义和住宅小区'));
const list=readFileSync(new URL('../src/components/talent/UnifiedPolicyList.tsx',import.meta.url),'utf8');
assert.ok(list.includes("p.id==='sd-dongying-talent-2026'"));
const dongyingHousing=TALENT_HOUSING_RECORDS.filter(h=>h.city==='东营');
const youlai=dongyingHousing.find(h=>h.id==='dy-you-lai-city-center-2026-verified');
assert.ok(youlai,'Existing project verified by governmental acknowledgement must appear in housing');
assert.equal(assessHousing(youlai,'2026-10-30').grade,'B');
assert.ok(youlai.sourceUrl==='https://www.jiwei.gov.cn/news_content.thtml?contentId=46194');
assert.equal(youlai.applyUrl,undefined,'Unknown 2026 application URL must remain absent');
assert.ok(youlai.statusNote.includes('未核实'));
assert.ok(dongyingHousing.every(h=>h.sourceUrl.includes('.gov.cn')),'Only government-origin primary evidence enters published housing records');
assert.ok(!dongyingHousing.some(h=>h.units.includes('70套')),'River-port expired media-only project stays outside database');
console.log('Dongying V5.1 PASS: archived old policies, 2026 transition guide, one government-confirmed housing project, unverified legacy leads isolated.');
