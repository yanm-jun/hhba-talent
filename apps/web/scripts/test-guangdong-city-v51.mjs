import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const here=path.dirname(fileURLToPath(import.meta.url));
const data=p=>readFileSync(path.join(here,'../src/data',p),'utf8');
const policy=data('guangdongPolicyRecords.ts'),housing=data('guangdongHousingRecords.ts');
const policyIndex=data('talentPolicyRecords.ts'),housingIndex=data('talentHousingRecords.ts'),registry=data('talentCityRegistry.ts');
const cities=['广州','深圳','佛山','东莞','珠海','中山','惠州','江门','肇庆','汕头','潮州','揭阳','汕尾','湛江','茂名','阳江','韶关','清远','云浮','河源','梅州'];
assert.equal(cities.length,21);
for(const city of cities)assert.ok(registry.includes('|'+city+'市|广东省|'),'Guangdong city missing from nationwide index '+city);
assert.ok(policyIndex.includes('...GUANGDONG_POLICY_RECORDS'));
assert.ok(housingIndex.includes('...GUANGDONG_HOUSING_RECORDS'));
const policyIds=[...policy.matchAll(/id:'([^']+)'/g)].map(x=>x[1]);
const housingIds=[...housing.matchAll(/id:'([^']+)'/g)].map(x=>x[1]);
assert.equal(policyIds.length,7);assert.equal(housingIds.length,2);
assert.equal(new Set([...policyIds,...housingIds]).size,9);
for(const city of ['广州','深圳','东莞','惠州'])assert.ok(policy.includes("city:'"+city+"'"),city);
for(const id of policyIds)assert.ok(id.startsWith('gd-'));
for(const id of housingIds)assert.ok(id.startsWith('gd-'));
for(const source of [policy,housing])assert.ok(!source.includes('https://example.com'));
for(const id of ['gd-sz-high-talent-rent-202608','gd-dg-guanai-home-202609','gd-hz-house-voucher-202604'])assert.ok(policy.includes(id));
assert.ok(housing.includes('非实时')&&housing.includes('待核实'));
console.log('PASS Guangdong branch: 21 city directory entries, 7 source-backed policies, 2 housing programs, nationwide registries; 17 cities pending policy verification');
