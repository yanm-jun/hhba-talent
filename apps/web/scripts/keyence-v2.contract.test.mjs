import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=p=>fs.readFileSync(p,'utf8');
const p=JSON.parse(read('src/data/employerProfiles/cn-autumn-157.json'));
assert.equal(p.id,'cn-autumn-157');
assert.equal(p.name,'基恩士');
assert.equal(p.englishName,'KEYENCE CHINA');
assert.equal(p.recruitment.url,'https://www.keyence.com.cn/ss/careers/recruitment.jsp');
assert.equal(p.jobs.length,1,'Only 1 2027 recruiting job is confirmed by KEYENCE China');
assert.equal(p.jobs[0].title,'销售工程师 / 销售（2027届秋季校园招聘）');
assert.equal(p.business.length,6);
assert.equal(p.jobs[0].majorUnrestricted,true,'2027 recruiting must stay open to all majors');
assert.equal(p.jobs[0].educationLabel.includes('专业不限'),true);
assert.equal(p.jobs[0].currentOpenVerified,false);
assert(p.jobs[0].summary.length>=110&&p.jobs[0].requirements.length>=230);
assert(p.jobs[0].requirements.includes('12,000')&&p.jobs[0].requirements.includes('14,000'),'Published salary must carry accurate undergraduate/graduate ranges');
assert(p.jobs[0].requirements.includes('2026年9月1日')&&p.jobs[0].requirements.includes('2027年8月31日'));
assert(p.jobs[0].city.includes('地点由公司分配'),'Cannot invent work city');
assert.equal(p.media.photos.length,2);
const page=read('src/pages/UnifiedV2CompanyPage.tsx');
const styles=read('src/styles/unified-v2-company.css');
assert(page.includes("keyence=id==='cn-autumn-157'"),'Use existing HHBA V2 template');
assert(['weipu','bodor','pxw','keyence'].every(name=>(page.match(/const detailedCards=([^;]+)/)?.[1]||'').split('||').includes(name)),'Detailed green expandable second-image card required');
assert(page.includes("if(keyence)return major==='专业不限'&&job.majorUnrestricted"),'Do not suppress unrestricted role');
assert(page.includes('data-hhba-recruitment-outbound="true"'),'Login-first official outbound');
assert(styles.includes('.hhba-v2-keyence .hhba-v2-company-role'));
assert(!p.jobs.some(j=>/研发工程师|财务专员|电气设计/.test(j.title)),'Business segments are not fabricated jobs');
const assets=[p.media.logo,...p.media.photos.map(x=>x.path)];
assert.equal(new Set(assets).size,3);
for(const filename of assets)assert(fs.existsSync('public/'+filename)&&fs.statSync('public/'+filename).size>2800,'Missing asset: '+filename);
const audit=JSON.parse(read('public/images/employer-profiles/cn-autumn-157/media-audit.json'));
assert.deepEqual(Object.keys(audit).sort(),['logo.webp','photo1.jpg','photo2.jpg']);
assert.equal(new Set(Object.values(audit).map(x=>x.sha256)).size,3);
console.log('KEYENCE_157_V2_CONTRACT_PASSED',JSON.stringify({jobs:1,services:6,assets:3,major:'unrestricted'}));
