assert(mech.every(j=>!j.id.includes('finance')),'Mechanical tab may not include unrelated jobs');
assert.equal(p.jobs.find(j=>j.id==='procure-sheet')?.category,'供应链 / 质量');
assert.equal(p.jobs.find(j=>j.id==='overseas-service')?.category,'营销 / 服务');
