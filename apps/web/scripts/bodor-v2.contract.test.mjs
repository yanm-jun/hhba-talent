import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=p=>fs.readFileSync(p,'utf8');
const p=JSON.parse(read('src/data/employerProfiles/cn-autumn-033.json'));
assert.equal(p.id,'cn-autumn-033');
assert.equal(p.name,'邦德激光');
assert.equal(p.displayName,'邦德激光');
