import {chromium} from 'playwright';
import {mkdirSync} from 'node:fs';
const base=(process.env.HHBA_TEST_BASE||'http://127.0.0.1:4173/hhba-talent/preview-employer/').replace(/\/$/,'');
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:980},locale:'zh-CN'});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const go=async(path)=>{await page.goto(base+path,{waitUntil:'domcontentloaded',timeout:40000})};
const at=async(path)=>{await page.waitForURL(url=>url.pathname===(new URL(base).pathname+path),{timeout:12000})};
mkdirSync('employer-review',{recursive:true});
try{
 await go('/');
 await page.getByRole('button',{name:/我要招人/}).click();
 await at('/employer/start');
 await page.getByRole('heading',{name:'首次入驻企业'}).waitFor();
 await page.getByRole('link',{name:/开始企业入驻/}).click();
 await at('/employer/onboarding-preview');
 await page.getByRole('heading',{name:'企业身份'}).waitFor();
 await page.getByText('我是 HR 或招聘负责人').click();
 await page.getByRole('button',{name:/下一步/}).click();
 await page.getByRole('heading',{name:'企业信息'}).waitFor();
 await page.getByPlaceholder('请输入营业执照上的企业全称').fill('验收演示企业（不是真实认证）');
 await page.getByPlaceholder('例如：山东省济南市').fill('山东省济南市');
 await page.getByRole('button',{name:/下一步/}).click();
 await page.getByRole('heading',{name:'经办人身份'}).waitFor();
 await page.getByPlaceholder('例如：人力资源负责人').fill('招聘经理');
 await page.getByRole('button',{name:/下一步/}).click();
 await page.getByRole('heading',{name:'核对规则'}).waitFor();
 await page.getByRole('button',{name:/预览企业工作台/}).click();
 await page.getByRole('alert').filter({hasText:'请先阅读并确认招聘和评分规则'}).waitFor();
 await page.getByLabel('我已阅读以上规则').check();
 await page.getByRole('button',{name:/预览企业工作台/}).click();
 await at('/employer/hub');
 await page.getByRole('heading',{name:'企业招聘概览'}).waitFor();
 await page.getByRole('heading',{name:'招聘管理'}).waitFor();
 await page.getByText('待评估',{exact:true}).first().waitFor();
 await page.screenshot({path:'employer-review/desktop-workbench.png',fullPage:true});
 const overview=await page.locator('.eh-main').innerText();
 if(/\b88\b|\b92\b/.test(overview))throw Error('FAKE_SCORES_PRESENT');
 await page.getByRole('link',{name:'信誉与善待'}).click();
 await at('/employer/growth');
 await page.getByRole('heading',{name:'企业成长档案'}).waitFor();
 await page.getByText('待独立核验').first().waitFor();
 await page.screenshot({path:'employer-review/growth-no-fake-scores.png',fullPage:true});
 await page.getByRole('link',{name:'HHBA 帮扶'}).click();
 await at('/employer/aid');
 await page.getByRole('heading',{name:'HHBA 企业发展帮扶'}).waitFor();
 await page.locator('textarea').fill('演示产品');
 await page.getByRole('button',{name:'检查准备情况'}).click();
 await page.getByText(/尚未提交或保存到 HHBA/).waitFor();
 await page.getByRole('link',{name:'企业公开视图'}).click();
 await at('/employer/public');
 await page.getByRole('heading',{name:'企业公开档案（结构预览）'}).waitFor();
 await page.getByRole('button',{name:'员工'}).click();
 await page.getByRole('link',{name:/查看员工反馈流程/}).waitFor();
 await page.screenshot({path:'employer-review/public-employee-view.png',fullPage:true});
 await page.getByRole('link',{name:'现有招聘管理'}).click();
 await at('/employer/workspace');
 await page.getByText(/企业功能预览版/).waitFor();
 await page.getByRole('button',{name:/待连接企业 API 后开放保存/}).waitFor();
 await go('/employer/growth/');
 await page.getByRole('heading',{name:'企业成长档案'}).waitFor();
 await page.setViewportSize({width:390,height:844});
 await go('/');
 await page.getByRole('button',{name:/我要招人/}).click();
 await page.getByRole('link',{name:/进入企业工作台/}).click();
 await at('/employer/hub');
 await page.getByRole('heading',{name:'企业招聘概览'}).waitFor();
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>document.documentElement.clientWidth+3);
 if(overflow)throw Error('MOBILE_HORIZONTAL_OVERFLOW');
 await page.screenshot({path:'employer-review/mobile-workbench.png',fullPage:true});
 if(errors.length)throw Error('BROWSER_PAGE_ERRORS '+JSON.stringify(errors));
 console.log('HHBA_EMPLOYER_HUB_BROWSER_OK',JSON.stringify({onboardingSteps:4,recruitmentReusable:true,noFakeScores:true,aidNoSubmission:true,publicView:true,mobile:true,screenshots:4}));
}finally{await browser.close()}
