import assert from 'node:assert/strict';
import {mkdirSync,writeFileSync} from 'node:fs';
import {chromium} from 'playwright';
const base=process.env.HHBA_TEST_BASE||'http://127.0.0.1:4173/hhba-talent/preview-anker/';
const out='anker-preview-evidence';mkdirSync(out,{recursive:true});
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
try{
 const page=await browser.newPage({viewport:{width:1440,height:960},locale:'zh-CN'});
 const jsErrors=[];page.on('pageerror',e=>jsErrors.push(e.message));
 await page.goto(base+'companies/autumn/cn-autumn-008',{waitUntil:'domcontentloaded'});
 await page.locator('[data-employer-id="cn-autumn-008"]').waitFor({timeout:20000});
 assert.match(await page.locator('h1').first().innerText(),/安克创新/);
 const logo=page.locator('.hhba-kpmg-logo img');
 assert.match(await logo.getAttribute('src'),/cn-autumn-008\.svg/);
 await page.waitForFunction(()=>{const img=document.querySelector('.hhba-kpmg-logo img');return img?.complete&&img.naturalWidth>0});
 assert.equal(await page.locator('.hhba-kpmg-photo-grid img').count(),2);
 const roles=page.locator('.hhba-kpmg-role');assert.equal(await roles.count(),24);
 const majors=page.locator('.hhba-major-quick-list');
 assert.equal(await majors.locator('input').count(),0);
 await majors.getByRole('button',{name:/人工智能/}).click();
 const matches=await roles.count();assert(matches>0&&matches<24,'Major selector should filter 24 roles: '+matches);
 await page.screenshot({path:out+'/desktop.png',fullPage:true});
 await roles.first().getByRole('link',{name:/查看/}).click();
 await page.waitForURL(/\/candidate\/jobs\/cn-v2-anker-/, {timeout:15000});
 await page.waitForFunction(()=>document.body.innerText.includes('安克创新'),null,{timeout:18000});
 assert.match(await page.locator('body').innerText(),/安克创新/);
 await page.goto(base+'candidate/jobs',{waitUntil:'domcontentloaded'});
 const query=page.getByRole('textbox',{name:'自然语言搜索岗位'});
 await query.fill('Anker');
 await page.waitForFunction(()=>[...document.querySelectorAll('.unified-job-card')].length>0&&[...document.querySelectorAll('.unified-job-card')].every(e=>e.textContent.includes('安克创新')),{timeout:18000});
 const englishHits=await page.locator('.unified-job-card').count();assert(englishHits>0);
 await query.fill('安克创新');
 await page.waitForFunction(()=>[...document.querySelectorAll('.unified-job-card')].length>0&&[...document.querySelectorAll('.unified-job-card')].every(e=>e.textContent.includes('安克创新')),{timeout:18000});
 await page.screenshot({path:out+'/search.png',fullPage:true});
 const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,deviceScaleFactor:2,locale:'zh-CN'});
 await mobile.goto(base+'companies/autumn/cn-autumn-008',{waitUntil:'domcontentloaded'});
 await mobile.locator('[data-employer-id="cn-autumn-008"]').waitFor({timeout:20000});
 assert.equal(await mobile.locator('.hhba-kpmg-photo-grid img').count(),2);
 assert.equal(await mobile.locator('.hhba-kpmg-role').count(),24);
 await mobile.screenshot({path:out+'/mobile.png',fullPage:true});
 assert.deepEqual(jsErrors,[]);
 writeFileSync(out+'/result.txt',JSON.stringify({logo:'PASS',photos:2,totalJobs:24,filteredJobs:matches,englishSearchHits:englishHits,jobDetail:'PASS',chineseSearch:'PASS',mobile:'PASS'}));
 console.log('HHBA_ANKER_BROWSER_DESKTOP_MOBILE_SEARCH_JOBS_PASS');
}finally{await browser.close()}
