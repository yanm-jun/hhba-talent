-- Career Library V1.1 exact-major overrides correct group-level false priorities.
-- Specific major wins; group-level routes are fallback for majors without curated mapping.
-- These pathways guide SEARCH, never determine whether a person meets job qualifications.
CREATE TABLE IF NOT EXISTS hhba_library_major_role_paths (
 major_code TEXT NOT NULL REFERENCES hhba_library_majors(major_code),
 role_id TEXT NOT NULL REFERENCES hhba_library_role_families(role_id),
 route_type TEXT NOT NULL CHECK(route_type IN ('DIRECT','CROSS_SKILL')),
 priority INTEGER NOT NULL CHECK(priority BETWEEN 1 AND 99),
 rationale TEXT NOT NULL DEFAULT '职业搜索导航，必须阅读真实岗位任职要求',
 PRIMARY KEY(major_code,role_id)
);
CREATE INDEX IF NOT EXISTS idx_hhba_library_major_role_priority
 ON hhba_library_major_role_paths(major_code,route_type,priority);
