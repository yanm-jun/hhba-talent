-- HHBA Career Library V1: user-major navigation -> job families -> industry halls -> employer sources.
-- Professional names/codes: PRC Ministry of Education official catalogue (2026); currently a curated PARTIAL subset, not all 883 majors.
-- Editorial pathway hints are discovery routes, NEVER degree eligibility or live-job claims.
-- Do not infer any candidate's major from their personal resume in this migration.
CREATE TABLE IF NOT EXISTS hhba_library_halls (
 hall_id TEXT PRIMARY KEY,
 display_name TEXT NOT NULL UNIQUE,
 description TEXT NOT NULL,
 catalog_version TEXT NOT NULL DEFAULT 'HHBA_LIBRARY_V1',
 sort_order INTEGER NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS hhba_library_hall_sections (
 section_id TEXT PRIMARY KEY, hall_id TEXT NOT NULL REFERENCES hhba_library_halls(hall_id),
 display_name TEXT NOT NULL, sort_order INTEGER NOT NULL,
 UNIQUE(hall_id,display_name)
);
CREATE TABLE IF NOT EXISTS hhba_library_major_groups (
 major_group_id TEXT PRIMARY KEY, display_name TEXT NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS hhba_library_majors (
 major_code TEXT PRIMARY KEY,
 display_name TEXT NOT NULL,
 major_group_id TEXT NOT NULL REFERENCES hhba_library_major_groups(major_group_id),
 degree_level TEXT NOT NULL DEFAULT 'undergraduate' CHECK(degree_level='undergraduate'),
 catalog_year INTEGER NOT NULL DEFAULT 2026,
 source_url TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_hhba_library_major_name ON hhba_library_majors(display_name);
CREATE TABLE IF NOT EXISTS hhba_library_role_families (
 role_id TEXT PRIMARY KEY, display_name TEXT NOT NULL UNIQUE, keyword_examples TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS hhba_library_major_group_role_paths (
 major_group_id TEXT NOT NULL REFERENCES hhba_library_major_groups(major_group_id),
 role_id TEXT NOT NULL REFERENCES hhba_library_role_families(role_id),
 pathway_kind TEXT NOT NULL DEFAULT 'POSSIBLE' CHECK(pathway_kind IN ('POSSIBLE','ADJACENT')),
 note TEXT NOT NULL DEFAULT '导航线索，不代表岗位专业准入资格',
 PRIMARY KEY(major_group_id,role_id)
);
CREATE TABLE IF NOT EXISTS hhba_library_hall_role_paths (
 hall_id TEXT NOT NULL REFERENCES hhba_library_halls(hall_id),
 role_id TEXT NOT NULL REFERENCES hhba_library_role_families(role_id),
 PRIMARY KEY(hall_id,role_id)
);
CREATE TABLE IF NOT EXISTS hhba_library_employer_halls (
 employer_source_id TEXT NOT NULL REFERENCES hhba_reviewed_recruitment_sources(id) ON DELETE CASCADE,
 hall_id TEXT NOT NULL REFERENCES hhba_library_halls(hall_id),
 membership_type TEXT NOT NULL CHECK(membership_type IN ('PRIMARY','SECONDARY')),
 section_id TEXT REFERENCES hhba_library_hall_sections(section_id),
 classification_basis TEXT NOT NULL,
 reviewed_at TEXT NOT NULL,
 PRIMARY KEY(employer_source_id,hall_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_hhba_library_employer_single_primary ON hhba_library_employer_halls(employer_source_id) WHERE membership_type='PRIMARY';
CREATE INDEX IF NOT EXISTS idx_hhba_library_hall_employers ON hhba_library_employer_halls(hall_id,membership_type);
CREATE TABLE IF NOT EXISTS hhba_library_employer_role_scopes (
 employer_source_id TEXT NOT NULL REFERENCES hhba_reviewed_recruitment_sources(id) ON DELETE CASCADE,
 role_id TEXT NOT NULL REFERENCES hhba_library_role_families(role_id),
 scope_kind TEXT NOT NULL DEFAULT 'BUSINESS_POSSIBILITY' CHECK(scope_kind='BUSINESS_POSSIBILITY'),
 evidence_note TEXT NOT NULL,
 PRIMARY KEY(employer_source_id,role_id)
);
